def current_language():
    '''Trả về mã ngôn ngữ hiện tại.'''
    global _current_language
    if _current_language is None:
        _current_language = load_language()
    return _current_language


def set_language(language):
    '''Đặt ngôn ngữ mới và lưu vào QSettings.'''
    global _current_language
    _current_language = normalize_language(language)
    save_language(_current_language)
    return _current_language


def supported_languages():
    '''Trả về tuple các ngôn ngữ được hỗ trợ.'''
    return SUPPORTED_LANGUAGES


def language_name(language):
    '''Trả về tên hiển thị của ngôn ngữ.'''
    code = normalize_language(language)
    names = {
        'km': 'ភាសាខ្មែរ',
        'vi': 'Tiếng Việt',
        'en': 'English',
    }
    return names.get(code, code)


def t(text, **kwargs):
    '''Dịch chuỗi UI sang ngôn ngữ hiện tại (nếu có bản dịch).

    Hỗ trợ template: t('Xin chào {name}', name='World')
    '''
    lang = current_language()
    if lang == 'en':
        value = _EN.get(text, text)
    elif lang == 'km':
        value = _KM.get(text, text)
    else:
        value = text
    if kwargs:
        try:
            value = value.format(**kwargs)
        except (KeyError, IndexError):
            pass
    return value
